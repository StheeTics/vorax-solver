// Writes wasm/src/data.rs: the tables the WebAssembly futures need (pools in deal order, odds), from the same data
// the JavaScript engine uses, so the two can't drift apart.
import { writeFileSync } from 'node:fs'
import { POTIONS, NORMAL_POOL, BOX_POOL, SUPREME_POOL } from '@/data/potions'
import { INSTRUMENTS, BASIC_POOL, ADVANCED_POOL } from '@/data/instruments'
import { LIVE_WEIGHTS } from '@/data/liveWeights'
import { RARITIES } from '@/data/archetypes'

const f = (x: number) => (Number.isInteger(x) ? `${x}.0` : `${x}`)
const arr = (xs: (number | string)[], t: string) => `[${xs.join(', ')}] as [${t}; ${xs.length}]`
const maxId = Math.max(...POTIONS.map(p => p.id))
const byId = (fn: (p: (typeof POTIONS)[number]) => string, fallback: string) =>
  Array.from({ length: maxId + 1 }, (_, id) => { const p = POTIONS.find(q => q.id === id); return p ? fn(p) : fallback })
const targeting = (p: (typeof POTIONS)[number]) => (typeof p.targeting === 'object' ? `T::Box(${p.targeting.box})` : p.targeting === 'auto' ? 'T::Auto' : p.targeting === 'select1' ? 'T::One' : 'T::OneOrTwo')
const timing = (d: (typeof INSTRUMENTS)[number]) => {
  const t = d.timing
  if (t.kind === 'end') return 'Timing::End'
  if (t.kind === 'periodic') return `Timing::Every(${t.every})`
  return `Timing::On(&[${t.on.map(e => `Ev::${e[0].toUpperCase()}${e.slice(1)}`).join(', ')}])`
}
const maxInstr = Math.max(...INSTRUMENTS.map(d => d.id))
const instrById = <T,>(fn: (d: (typeof INSTRUMENTS)[number]) => T, fallback: T) => Array.from({ length: maxInstr + 1 }, (_, id) => { const d = INSTRUMENTS.find(x => x.id === id); return d ? fn(d) : fallback })
const w = (table: Record<string, number>) => (p: { name: string }) => f(table[p.name] ?? 1)

const out = `// Generated by scripts/sim/wasmData.ts from src/data: don't edit.
#![allow(dead_code)]
use crate::engine::{T, Timing, Ev};

pub const POTIONS: usize = ${maxId + 1};
pub const INSTRUMENTS: usize = ${maxInstr + 1};
pub const SUPREME_CHANCE: f64 = ${f(LIVE_WEIGHTS.supremeChance)};
/** normal, magic, rare, boss */
pub const SPAWN: [f64; 4] = [${RARITIES.map(r => f(LIVE_WEIGHTS.spawnRarity[r])).join(', ')}];
pub const NORMAL_POOL: &[u8] = &[${NORMAL_POOL.map(p => p.id).join(', ')}];
pub const BOX_POOL: &[u8] = &[${BOX_POOL.map(p => p.id).join(', ')}];
pub const SUPREME_POOL: &[u8] = &[${SUPREME_POOL.map(p => p.id).join(', ')}];
/** by potion id */
pub const TARGETING: [T; ${maxId + 1}] = [${byId(targeting, 'T::Auto').join(', ')}];
pub const IS_SUPREME: [bool; ${maxId + 1}] = [${byId(p => String(p.rarity === 'supreme'), 'false').join(', ')}];
pub const POTION_OFFER: [f64; ${maxId + 1}] = [${byId(w(LIVE_WEIGHTS.potionOffer), '1.0').join(', ')}];
pub const BOX_OFFER: [f64; ${maxId + 1}] = [${byId(w(LIVE_WEIGHTS.boxOffer), '1.0').join(', ')}];
pub const BASIC_POOL: &[u8] = &[${BASIC_POOL.map(d => d.id).join(', ')}];
pub const ADVANCED_POOL: &[u8] = &[${ADVANCED_POOL.map(d => d.id).join(', ')}];
/** by instrument id */
pub const BASIC_OFFER: [f64; ${maxInstr + 1}] = [${instrById(d => (d.pool === 'basic' ? f(LIVE_WEIGHTS.instrumentOffer.basic[d.name] ?? 1) : '1.0'), '1.0').join(', ')}];
pub const ADVANCED_OFFER: [f64; ${maxInstr + 1}] = [${instrById(d => (d.pool === 'advanced' ? f(LIVE_WEIGHTS.instrumentOffer.advanced[d.name] ?? 1) : '1.0'), '1.0').join(', ')}];
pub const TIMING: [Timing; ${maxInstr + 1}] = [${instrById(timing, 'Timing::End').join(', ')}];
pub const HAS_END: [bool; ${maxInstr + 1}] = [${instrById(d => String(!!d.endOfRound), 'false').join(', ')}];
`
void arr
writeFileSync('wasm/src/data.rs', out)
console.log('wrote wasm/src/data.rs')
